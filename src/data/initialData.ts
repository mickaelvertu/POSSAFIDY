// Helper to determine category for resale products
function getCategoryForProduct(name: string, ref: string): string {
  const n = name.toUpperCase();
  if (n.startsWith("BAUME") || n.includes("ALAVONTO") || n.includes("RADRIAKA") || n.includes("RAMBIAZINA")) {
    return "cat-baumes";
  }
  if (n.startsWith("HE ") || n.includes("CYPRES") || n.includes("RAVINTSARA") || n.includes("SARO") || n.includes("KATRAFAY")) {
    return "cat-he";
  }
  if (n.startsWith("ARGILE") || n.includes("CATAPLASME")) {
    return "cat-argiles";
  }
  if (n.includes("MIEL") || n.includes("SPIRULINE") || n.includes("NONI")) {
    return "cat-miel";
  }
  if (n.startsWith("SAVON") || n.includes("SAVLAH") || n.includes("CREME") || n.includes("LOTION") || n.includes("EAU MICELLAIRE")) {
    return "cat-savons";
  }
  return "cat-tisanes";
}

